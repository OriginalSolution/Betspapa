const goal = (minute: number, side: 'home' | 'away', player: string, detail?: ScriptEvent['detail']): ScriptEvent => ({
  minute,
  type: 'goal',
  side,
  player,
  detail,
});
const yellow = (minute: number, side: 'home' | 'away', player: string): ScriptEvent => ({
  minute,
  type: 'yellow',
  side,
  player,
});
const red = (minute: number, side: 'home' | 'away', player: string): ScriptEvent => ({
  minute,
  type: 'red',
  side,
  player,
});
const ht = (): ScriptEvent => ({ minute: 45, type: 'ht' });
const ft = (minute = 90): ScriptEvent => ({ minute, type: 'ft' });

